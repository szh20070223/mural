def guidelines_for(diseases: list[str]) -> dict[str, dict[str, str]]:
    """只取卡片上实际出现的病害对应的原则。

    为什么要过滤：把 8 条全部塞给模型，它会忍不住给没出现在卡上的
    病害也写建议，结果卡片上的建议和标注的区域对不上。
    """
    return {name: GUIDELINES[name] for name in diseases if name in GUIDELINES}
