# 处置原则参考表
# =============================================================================
# 这张表是 C 成稿阶段的"知识底座"。为什么要有它：
#
#   如果直接让模型"给 1-2 条保护建议"，它会写出一堆听起来很专业、
#   实际上不能落地的话，比如"建议采用纳米氢氧化钙加固"——
#   那是修复师的判断，不是 AI 能给的，而且写错了要担责。
#
#   这张表把 AI 可以说的话**收窄**到一个范围：
#   只允许"记录、监测、限制接触、控制环境、数字展示"这一类，
#   并且每一条都写明风险。超出这个范围的建议，一律不许生成。
#
# 内容来源：文物保护通行的"最小干预"原则（先记录、先监测、再干预），
# 以及各病害的常见劣化机理。**这不是专业鉴定标准**，
# 只是让 AI 的话落在常识范围内——真正的判断必须由人做。
#
# 加新病害时：先在 src/schemas.py 的 DiseaseType 里加，
# 再在这里补一条，否则 C 拿不到原则会拒绝出稿。
# =============================================================================

